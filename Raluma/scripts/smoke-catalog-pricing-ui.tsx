import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { MemoryRouter } from 'react-router-dom';
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: () => null, setItem: () => {}, removeItem: () => {} }, configurable: true });
const { useAuthStore } = await import('../src/store/authStore');
const { default: Catalog } = await import('../src/pages/HardwareCatalogPage');
const { default: SystemPricing } = await import('../src/pages/ConstructionPricingPage');
useAuthStore.setState({ user: { id: 1, username: 'admin', display_name: 'Admin', role: 'admin', customer: null, can_manage_prices: true, is_active: true, created_at: '', last_login: null } });
const catalog = renderToStaticMarkup(<MemoryRouter><Catalog /></MemoryRouter>);
assert.doesNotMatch(catalog, /Готовые правила|Вернуть правило|В готовой конструкции|Отходы/);
assert.match(catalog, /Настройка конструкций/);
const systems = renderToStaticMarkup(<MemoryRouter><SystemPricing /></MemoryRouter>);
assert.match(systems, /Слайд 1 ряд/); assert.match(systems, /Слайд 2 ряда/); assert.match(systems, /ЦС/);
assert.match(systems, /Сохранить систему/);
useAuthStore.setState({ user: null });
assert.equal(renderToStaticMarkup(<MemoryRouter><SystemPricing /></MemoryRouter>), '');
console.log('Catalog separation and pricing access smoke passed.');
