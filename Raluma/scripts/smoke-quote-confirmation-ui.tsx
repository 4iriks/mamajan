import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import type { PublicQuote } from '../src/api/quotes';
import { captureQuoteConfirmation } from '../src/utils/quoteConfirmation';
import { QuoteConfirmationDialog } from '../src/components/QuoteConfirmationDialog';

const quote = (amount: string, status: PublicQuote['status']): PublicQuote => ({ project: { id: 7, number: '7', customer: 'Тест' }, revision: 1, status, fixed_at: null, currency: 'RUB', money_presentation_version: 2, lines: [], totals: { before_discount: amount, discount: '0', subtotal: amount, grand_total: amount, document_before_discount: amount, document_discount: '0', document_grand_total: amount }, validity_days: 14, valid_until: '', manufacturing_term: '', payment_terms: '', discounts: [], missing_price_count: 0, warnings: [], export_allowed: true, stale: false });
const current = quote('1000.00', 'fixed');
const pending = quote('800.00', 'draft');
const snapshot = captureQuoteConfirmation('revision', 7, pending, 'preview-A', current)!;
assert.deepEqual(snapshot, { action: 'revision', projectId: 7, previewToken: 'preview-A', amount: '800.00', previousAmount: '1000.00' });
pending.totals.grand_total = '900.00';
current.totals.grand_total = '1100.00';
const refreshed = captureQuoteConfirmation('revision', 7, pending, 'preview-B', current)!;
assert.equal(snapshot.amount, '800.00', 'open confirmation must retain the amount actually viewed');
assert.equal(snapshot.previousAmount, '1000.00');
assert.equal(snapshot.previewToken, 'preview-A', 'confirmation must never adopt a later token silently');
assert.equal(refreshed.amount, '900.00', 'a new confirmation captures refreshed values');
assert.equal(refreshed.previewToken, 'preview-B');
assert.equal(captureQuoteConfirmation('freeze', 7, { ...pending, export_allowed: false }, 'preview-A', null), null);
assert.equal(captureQuoteConfirmation('freeze', 7, pending, '', null), null);
assert.equal(captureQuoteConfirmation('revision', 7, pending, 'preview-A', null), null);
const revisionHtml = renderToStaticMarkup(<QuoteConfirmationDialog confirmation={snapshot} busy={false} onConfirm={() => {}} onCancel={() => {}} />);
assert.match(revisionHtml, /role="alertdialog"/);
assert.match(revisionHtml, /aria-modal="true"/);
assert.match(revisionHtml, /Подтвердить новую редакцию КП/);
assert.match(revisionHtml, /1\s000,00/);
assert.match(revisionHtml, /800,00/);
assert.doesNotMatch(revisionHtml, /900,00/);
assert.match(revisionHtml, /Отмена/);
assert.match(revisionHtml, /Подтвердить и зафиксировать/);
assert.match(revisionHtml, /подтвердить её ещё раз/);
const first = captureQuoteConfirmation('freeze', 7, pending, 'preview-B', null)!;
const firstHtml = renderToStaticMarkup(<QuoteConfirmationDialog confirmation={first} busy={true} onConfirm={() => {}} onCancel={() => {}} />);
assert.match(firstHtml, /Подтвердить фиксацию КП/);
assert.doesNotMatch(firstHtml, /Сейчас зафиксировано/);
assert.equal((firstHtml.match(/disabled=""/g) || []).length, 2, 'confirm and cancel must both be blocked during saving');
console.log('Quote confirmation smoke passed: immutable reviewed token/amount, old/new sums, accessible in-app confirmation and blocked states.');
